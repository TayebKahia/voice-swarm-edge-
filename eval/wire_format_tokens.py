#!/usr/bin/env python3
"""How many decode tokens the wire format saves by omitting null fields.

Master Ch3 argues that omitting absent slots is a latency decision, not a style. The
argument needs a measured token count, and "a representative command runs to roughly
40 tokens" was a design estimate that nothing in results/ had ever measured. This
module measures it over the 200 golden labels, with each deployed model's own
tokeniser, against the two ways a null-carrying format could be written:

- **intent nulls**: every slot the command's own intent declares, absent ones as null;
- **schema nulls**: every slot any intent declares, i.e. one flat object for all ten.

The first is the smaller, more defensible counterfactual; the second is what a flat
JSON Schema would force. Both are reported, so the chapter can state which one it
means. Seconds are at the selected configuration's measured throughput
(results/thermal_headroom.md) and at the 20 tok/s floor.

Output (regenerated, never hand-edited):
    results/wire_format_tokens.md

Usage:
    python eval/wire_format_tokens.py
"""

from __future__ import annotations

import json
import statistics
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from schema.schema import KEY_ORDER  # noqa: E402

TOKENIZE = Path.home() / "llama.cpp" / "build" / "bin" / "llama-tokenize"
GOLDEN = REPO / "data" / "test_golden.jsonl"
OUT = REPO / "results" / "wire_format_tokens.md"
MODELS = ("qwen2.5-0.5b-instruct", "smollm2-360m-instruct", "llama-3.2-1b-instruct")
SELECTED = "qwen2.5-0.5b-instruct"
FLOOR_TOK_S = 20.0

#: Every slot any intent declares, in first-declaration order.
UNION = list(dict.fromkeys(k for keys in KEY_ORDER.values() for k in keys))


def n_tokens(gguf: Path, text: str) -> int:
    out = subprocess.run([str(TOKENIZE), "-m", str(gguf), "-p", text, "--ids", "--no-bos",
                          "--log-disable"], capture_output=True, text=True, check=True).stdout
    return len(json.loads([line for line in out.splitlines() if line.startswith("[")][-1]))


def compact(obj: dict) -> str:
    return json.dumps(obj, separators=(",", ":"))


def selected_tok_s() -> float:
    lines = (REPO / "results" / "thermal_headroom.md").read_text().splitlines()
    header = next(i for i, line in enumerate(lines) if line.startswith("| Config"))
    cols = [c.strip() for c in lines[header].strip("|").split("|")]
    for line in lines[header + 2:]:
        cells = [c.strip() for c in line.strip("|").split("|")]
        if cells[0] == f"{SELECTED}-Q4_K_M" and cells[1] == "cooled":   # the run of record
            return float(cells[cols.index("tok/s")])
    raise SystemExit(f"no cooled {SELECTED}-Q4_K_M row in results/thermal_headroom.md")


def run() -> int:
    labels = [json.loads(json.loads(line)["target"]) for line in GOLDEN.read_text().splitlines()]
    tok_s = selected_tok_s()
    rows = []
    for name in MODELS:
        gguf = REPO / "gguf" / f"{name}-Q4_K_M.gguf"
        c = [n_tokens(gguf, compact(t)) for t in labels]
        i = [n_tokens(gguf, compact({k: t.get(k) for k in KEY_ORDER[t["intent"]]})) for t in labels]
        u = [n_tokens(gguf, compact({k: t.get(k) for k in UNION})) for t in labels]
        rows.append((name, statistics.mean(c), statistics.mean(i), statistics.mean(u)))

    out = ["# Wire-format token counts (golden labels)", "",
           f"Generated by `eval/wire_format_tokens.py` over the {len(labels)} labels of "
           "`data/test_golden.jsonl`, tokenised with each model's Q4_K_M GGUF (`llama-tokenize "
           "--no-bos`). Means per label.", "",
           "| Model | Wire format | Intent nulls | Schema nulls | Saved vs intent | Saved vs schema |",
           "|---|---|---|---|---|---|"]
    for name, c, i, u in rows:
        out.append(f"| {name} | {c:.1f} | {i:.1f} | {u:.1f} | {i - c:.1f} | {u - c:.1f} |")
    _, c, i, u = next(r for r in rows if r[0] == SELECTED)
    out += ["", f"Decode time saved per command, {SELECTED} (selected configuration):", "",
            "| Counterfactual | Tokens saved | s at measured tok/s | s at 20 tok/s floor |",
            "|---|---|---|---|",
            f"| Intent nulls | {i - c:.1f} | {(i - c) / tok_s:.2f} (at {tok_s:.2f} tok/s) | {(i - c) / FLOOR_TOK_S:.2f} |",
            f"| Schema nulls | {u - c:.1f} | {(u - c) / tok_s:.2f} (at {tok_s:.2f} tok/s) | {(u - c) / FLOOR_TOK_S:.2f} |",
            ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(run())
