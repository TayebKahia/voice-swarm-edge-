#!/usr/bin/env python3
"""How many golden-split errors keep the reference intent? The number behind a Ch4 claim.

Intent macro-F1 above 0.95 says the intents are mostly right; it does not say what share
of the *errors* are parameter errors inside a correctly identified intent, which is the
claim the Results chapter makes about them. This script counts it directly: an error is an
item whose exact match is 0, and it keeps the intent when the dispatched intent equals the
reference intent -- the same `dispatched` field intent macro-F1 is computed from, so the
two figures cannot disagree about what "the intent" is.

Deployed surface, grammar on, `test_golden`, all six artefacts, re-scored from the per-item
predictions in `results/surface_b_preds/` by `eval/metrics.py`.

Usage:
    python eval/error_intents.py
"""

from __future__ import annotations

import json
import logging
import sys
from pathlib import Path

if __package__ in (None, ""):  # `python eval/error_intents.py`
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from eval.metrics import Prediction, score_predictions

REPO = Path(__file__).resolve().parent.parent
PREDICTIONS = REPO / "results" / "surface_b_preds"
OUT_MD = REPO / "results" / "golden_error_intents.md"

MODELS = ("llama-3.2-1b-instruct", "qwen2.5-0.5b-instruct", "smollm2-360m-instruct")
QUANTS = ("Q4_K_M", "Q8_0")
SPLIT = "test_golden"


def errors_keeping_intent(predictions: list[Prediction]) -> tuple[int, int]:
    """(errors whose dispatched intent is the reference intent, errors)."""
    errors = [p for p in predictions if not p.correct]
    return sum(1 for p in errors if p.dispatched == p.gold_intent), len(errors)


def _load(model: str, quant: str) -> list[Prediction]:
    path = PREDICTIONS / f"{model}-{quant}_{SPLIT}.jsonl"
    if not path.is_file():
        raise SystemExit(f"missing {path.relative_to(REPO)} -- run eval/surface_b.py")
    rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return score_predictions([r["raw"] for r in rows], [r["gold"] for r in rows])


def run() -> int:
    logging.getLogger("schema.validate").setLevel(logging.CRITICAL)
    lines = [
        f"### Golden-split errors that keep the reference intent (`{SPLIT}`, deployed surface)",
        "",
        "An error is an item with exact match 0; it keeps the intent when the dispatched intent",
        "equals the reference intent. Generated by `eval/error_intents.py` from",
        "`results/surface_b_preds/`.",
        "",
        "| Model | Quant | Errors | Keep the intent | Share |",
        "| :--- | :--- | ---: | ---: | ---: |",
    ]
    kept_total = errors_total = 0
    for model in MODELS:
        for quant in QUANTS:
            kept, errors = errors_keeping_intent(_load(model, quant))
            kept_total, errors_total = kept_total + kept, errors_total + errors
            share = "--" if not errors else f"{kept / errors:.3f}"
            lines.append(f"| {model} | {quant} | {errors} | {kept} | {share} |")
    lines.append(f"| **all six** | | **{errors_total}** | **{kept_total}** "
                 f"| **{kept_total / errors_total:.3f}** |")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {OUT_MD.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(run())
